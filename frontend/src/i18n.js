const dicts = { 'zh-CN': zhCN, en, ja, ko, es, fr }

export const LANGS = [
  { value: 'zh-CN', label: '简体中文' },
  { value: 'en', label: 'English' },
  { value: 'ja', label: '日本語' },
  { value: 'ko', label: '한국어' },
  { value: 'es', label: 'Español' },
  { value: 'fr', label: 'Français' },
]

function detect() {
  try {
    const saved = localStorage.getItem('locale')
    if (saved && dicts[saved]) return saved
  } catch { /* ignore */ }
  const nav = (navigator.language || 'zh-CN').toLowerCase()
  if (nav.startsWith('en')) return 'en'
  if (nav.startsWith('ja')) return 'ja'
  if (nav.startsWith('ko')) return 'ko'
  if (nav.startsWith('es')) return 'es'
  if (nav.startsWith('fr')) return 'fr'
  return 'zh-CN'
}

export const locale = ref(detect())
document.documentElement.lang = locale.value

export function setLocale(l) {
  if (!dicts[l]) return
  locale.value = l
  document.documentElement.lang = l
  try { localStorage.setItem('locale', l) } catch { /* ignore */ }
}

export function t(key, params) {
  let s = dicts[locale.value]?.[key] ?? zhCN[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v)
  return s
}

/** 取数组/对象型词条（FAQ、套餐特性等），回退逻辑同 t */
export function tl(key) {
  return dicts[locale.value]?.[key] ?? zhCN[key] ?? []
}
